// Real PostgreSQL engine (PGlite), with a minimal stand-in for Supabase Auth.
// This does NOT test hosted Supabase configuration or e-mail delivery.
const { PGlite } = require(process.env.BG3RO_PGLITE_PATH || '../.qa/db-test/node_modules/@electric-sql/pglite');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const A = '11111111-1111-1111-1111-111111111111';
const B = '22222222-2222-2222-2222-222222222222';
const M = '33333333-3333-3333-3333-333333333333';
(async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role bypassrls; create schema auth;
      create table auth.users(id uuid primary key,is_anonymous boolean default false,raw_user_meta_data jsonb default '{}',raw_app_meta_data jsonb default '{}');
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims',true),'')::jsonb,'{}'::jsonb) $$;
      grant usage on schema auth to anon,authenticated;
      grant execute on function auth.uid() to anon,authenticated;
      insert into auth.users values('${A}'),('${B}'),('${M}');`);
    await db.exec(`create schema storage;
      create table storage.buckets(id text primary key,name text,public boolean default false,file_size_limit bigint,allowed_mime_types text[]);
      create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text references storage.buckets(id),name text,owner_id text,metadata jsonb,unique(bucket_id,name));
      alter table storage.objects enable row level security;
      grant usage on schema storage to anon,authenticated;
      grant select on storage.objects to anon,authenticated;
      grant insert,delete on storage.objects to authenticated;`);
    const migrations = path.join(__dirname, '../supabase/migrations');
    const baseline = ['20261017_bg3ro_portal.sql','20261017b_bg3ro_public_access.sql'];
    const following = fs.readdirSync(migrations).filter(name=>name.endsWith('.sql')&&!baseline.includes(name)).sort();
    for (const file of [...baseline,...following]) await db.exec(fs.readFileSync(path.join(migrations,file),'utf8'));
    await db.query('insert into bg3ro_private.moderators values($1)', [M]);
    const role = async (id = null) => {
      await db.exec('reset role');
      await db.query("select set_config('request.jwt.claim.sub',$1,false)", [id || '']);
      await db.exec(`set role ${id ? 'authenticated' : 'anon'}`);
    };
    const denied = async (sql, args = []) => assert.rejects(db.query(sql, args));
    const post = (author, title = 'O sugestie de traducere', parent = null) => db.query('insert into public.bg3ro_discussion_posts(author_id,author_name,title,body,parent_id) values($1,$2,$3,$4,$5) returning id,status', [author, 'Jucător', title, 'Un mesaj de test suficient de lung.', parent]);
    const report = author => db.query("insert into public.bg3ro_bug_reports(author_id,title,body,category,platform,mod_version) values($1,'Acord greșit','Un context de test suficient de lung pentru raport.','gender','windows','test') returning id,status", [author]);
    await role();
    assert.equal((await db.query('select * from public.bg3ro_project_status')).rows[0].translation_percent, 80);
    assert.equal((await db.query('select * from public.bg3ro_project_status')).rows[0].review_percent, 20);
    assert.equal((await db.query('select * from public.bg3ro_project_status')).rows[0].testing_percent, 20);
    assert.equal((await db.query('select * from public.bg3ro_discussion_posts')).rows.length, 0);
    await denied('select * from public.bg3ro_bug_reports');
    await denied('select * from bg3ro_private.moderators');
    await denied("update public.bg3ro_project_status set translation_percent=100");
    await denied("update public.bg3ro_project_status set about_body='Anonymous overwrite'");
    await assert.rejects(post(A));
    await role(A);
    assert.equal((await db.query('select public.bg3ro_is_moderator() as moderator')).rows[0].moderator, false);
    await assert.rejects(post(B));
    const first = (await post(A)).rows[0]; assert.equal(first.status, 'approved');
    const ownReport = (await report(A)).rows[0]; assert.equal(ownReport.status, 'new');
    await assert.rejects(post(A), /30 de secunde/);
    await denied("update public.bg3ro_discussion_posts set author_id=$1 where id=$2", [B,first.id]);
    assert.equal((await db.query("update public.bg3ro_discussion_posts set status='rejected' where id=$1 returning id", [first.id])).rows.length, 0);
    await denied("insert into public.bg3ro_discussion_posts(author_name,title,body,status) values('Fake','Fake title','Fake message longer','approved')");
    await role(B);
    assert.equal((await db.query("update public.bg3ro_project_status set about_body='Member overwrite' returning id")).rows.length,0);
    assert.equal((await db.query('select * from public.bg3ro_discussion_posts')).rows.length, 1);
    assert.equal((await db.query('select * from public.bg3ro_bug_reports')).rows.length, 0);
    assert.equal((await db.query('delete from public.bg3ro_bug_reports where id=$1 returning id', [ownReport.id])).rows.length, 0);
    await role(M);
    assert.equal((await db.query('select public.bg3ro_is_moderator() as moderator')).rows[0].moderator, true);
    assert.equal((await db.query('select * from public.bg3ro_bug_reports')).rows.length, 1);
    await role();
    assert.equal((await db.query('select * from public.bg3ro_discussion_posts')).rows.length, 1, 'New post immediately visible anonymously');
    await role(M);
    await db.query("update public.bg3ro_discussion_posts set status='rejected' where id=$1", [first.id]);
    await role();
    assert.equal((await db.query('select * from public.bg3ro_discussion_posts')).rows.length, 0, 'Post-publication hiding still works');
    await role(M);
    await db.query("update public.bg3ro_discussion_posts set status='approved' where id=$1", [first.id]);
    await db.query("update public.bg3ro_bug_reports set status='resolved',moderator_reply='Corectat în test.' where id=$1", [ownReport.id]);
    await db.query("insert into public.bg3ro_project_updates(title,body) values('Actualizare de test','Un text de test pentru actualizare.')");
    await db.query('update public.bg3ro_project_status set translation_percent=81 where id=1');
    await db.query('update public.bg3ro_project_status set review_percent=21,testing_percent=22 where id=1');
    await db.exec('reset role');
    const publicAvatar='https://cdn.discordapp.com/avatars/123456789/avatar_hash.png';
    await db.query("update auth.users set raw_app_meta_data=$1,raw_user_meta_data=$2 where id=$3",[{provider:'discord'},{avatar_url:publicAvatar},M]);
    await role(M);
    const release=(await db.query("insert into public.bg3ro_releases(kind,version,title,file_name,file_bytes,download_url,description) values('translation','avatar-test','Titlu ales','qa.zip',12,'https://github.com/Gabrielish/bg3ro/releases/download/qa/qa.zip','Descriere de test') returning id,author_avatar_url")).rows[0];
    assert.equal(release.author_avatar_url,publicAvatar,'Release avatar is set by trusted trigger');
    await denied("update public.bg3ro_releases set author_avatar_url='https://example.com/tracker.png' where id=$1",[release.id]);
    await role();
    assert.equal((await db.query('select author_avatar_url from public.bg3ro_releases where id=$1',[release.id])).rows[0].author_avatar_url,publicAvatar,'Public release avatar is readable without exposing auth');
    await role(M);
    await db.query("update public.bg3ro_project_status set about_title='Titlu de test',about_body='Descriere de test',about_note='' where id=1");
    await assert.rejects(db.query("update public.bg3ro_project_status set about_body='' where id=1"),/check constraint/);
    await role();
    assert.equal((await db.query('select * from public.bg3ro_discussion_posts')).rows.length, 1);
    assert.equal((await db.query('select * from public.bg3ro_project_updates')).rows.length, 1);
    assert.equal((await db.query('select * from public.bg3ro_project_status')).rows[0].translation_percent, 81);
    assert.equal((await db.query('select about_body from public.bg3ro_project_status')).rows[0].about_body,'Descriere de test');
    await role(B);
    const reply = (await post(B, 'Răspuns de test', first.id)).rows[0]; assert.equal(reply.status, 'approved');
    await role(A);
    assert.equal((await db.query('select * from public.bg3ro_bug_reports')).rows[0].moderator_reply, 'Corectat în test.');
    // Deleting a post must not remove the rate limit record.
    await db.query('delete from public.bg3ro_discussion_posts where id=$1', [first.id]);
    await assert.rejects(post(A), /30 de secunde/);
    // Privileged fixture clock manipulation; normal users cannot access this table.
    await db.exec('reset role');
    await db.query("update bg3ro_private.submission_limits set last_sent=now()-interval '31 seconds',submissions=20 where user_id=$1 and kind='bg3ro_discussion_posts'", [A]);
    await role(A); await assert.rejects(post(A), /zilnic/);
    await role(M);
    await assert.rejects(db.query('update public.bg3ro_project_status set translation_percent=101'));
    await assert.rejects(db.query('update public.bg3ro_project_status set review_percent=101'));
    await assert.rejects(db.query('update public.bg3ro_project_status set testing_percent=-1'));
    await role(B); await denied('select * from bg3ro_private.submission_limits');
    await db.exec('reset role');
    await db.exec(fs.readFileSync(path.join(__dirname,'../supabase/tests/contact-access.sql'),'utf8'));
    await db.exec(fs.readFileSync(path.join(__dirname,'../supabase/tests/statistics-access.sql'),'utf8'));
    await db.exec(fs.readFileSync(path.join(__dirname,'../supabase/tests/views-access.sql'),'utf8'));
    await db.exec(fs.readFileSync(path.join(__dirname,'../supabase/tests/compatibility-names.sql'),'utf8'));
    // Storage RLS and controlled attachment: private images must never leak to visitors.
    await db.exec('reset role');
    await db.query("select set_config('request.jwt.claim.sub',$1,false)",[M]);
    const photoReport=(await db.query("insert into public.bg3ro_bug_reports(author_id,title,body,category,platform,mod_version,is_public) values($1,'Screenshot test','Screenshot context sufficiently long','text','windows','test',true) returning id",[M])).rows[0];
    const privatePath=ownReport.id+'/screenshot.jpg',publicPath=photoReport.id+'/screenshot.jpg';
    const upload=(p,owner)=>db.query("insert into storage.objects(bucket_id,name,owner_id,metadata) values('bg3ro-report-images',$1,$2,'{\"mimetype\":\"image/jpeg\",\"size\":100}')",[p,owner]);
    await role(B); await assert.rejects(upload(publicPath,B));
    await role(A); await upload(privatePath,A);
    await denied('update public.bg3ro_bug_reports set screenshot_path=$1 where id=$2',[privatePath,ownReport.id]);
    await db.query('select public.bg3ro_attach_report_image($1)',[ownReport.id]);
    await role(B); await denied('select public.bg3ro_attach_report_image($1)',[ownReport.id]);
    assert.equal((await db.query('select * from storage.objects')).rows.length,0);
    await role(); await denied('select public.bg3ro_attach_report_image($1)',[ownReport.id]);
    assert.equal((await db.query('select * from storage.objects')).rows.length,0);
    await role(M); await upload(publicPath,M); await db.query('select public.bg3ro_attach_report_image($1)',[photoReport.id]);
    await role(); assert.equal((await db.query('select * from storage.objects')).rows.length,1);
    await role(M); await db.query('delete from public.bg3ro_bug_reports where id=$1',[photoReport.id]);
    await role(); assert.equal((await db.query('select * from storage.objects')).rows.length,0);
    await role(M); await db.query('delete from storage.objects where name=$1',[publicPath]);
    console.log('PASS: portal migrations, role isolation, column privileges, rate limits, contact inbox, screenshot upload/attachment ownership and public/private image isolation.');
  } finally { await db.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
